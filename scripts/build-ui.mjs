// Bundles src/ui/client.ts into a string module, so the page ships inside the package.
import { readFile, rm, writeFile } from 'node:fs/promises';
import { build } from 'tsup';

const outDir = '.ui-build';
await build({
  entry: { client: 'src/ui/client.ts' },
  format: ['iife'],
  outDir,
  minify: true,
  target: 'es2020',
  platform: 'browser',
  silent: true,
  dts: false,
  sourcemap: false,
  clean: true,
  config: false,
});
const code = await readFile(`${outDir}/client.global.js`, 'utf8');
await writeFile(
  'src/ui/client.generated.ts',
  `// Generated by scripts/build-ui.mjs. Do not edit.\nexport default ${JSON.stringify(code.trim())};\n`,
);
await rm(outDir, { recursive: true, force: true });
